from typing import Any


def _p(hid: str, statement: str, support: float = 0.4) -> dict[str, Any]:
    return {"hypothesis_id": hid, "statement": statement, "initial_support": support}


def _ev(
    content: str,
    evidence_class: str,
    reliability: float,
    *,
    cc: float = 0.9,
    pc: float = 0.9,
    status: str = "provisional",
    source: str = "reflection",
    session: int = 1,
    channel: str = "written",
    supports: list[str] | None = None,
    contradicts: list[str] | None = None,
    proposals: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    return {
        "content": content,
        "evidence_class": evidence_class,
        "reliability": reliability,
        "classification_confidence": cc,
        "provenance_confidence": pc,
        "classification_status": status,
        "source": f"{source}:session-{session}",
        "metadata": [["channel", channel], ["session", str(session)]],
        "supports": supports or [],
        "contradicts": contradicts or [],
        "proposals": proposals or [],
    }


def _x(
    version: str,
    committed: bool,
    inquiry: bool,
    predictions: list[str],
    anomaly: str | None,
    uncertainty: str,
) -> dict[str, Any]:
    return {
        "version": version, "committed": committed, "inquiry": inquiry,
        "predictions": predictions, "anomaly": anomaly, "uncertainty": uncertainty,
    }


