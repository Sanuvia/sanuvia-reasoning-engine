"""The official Sanuvia Phase 0 engineering review dataset.

A curated set of deterministic Test Cases that exercise every major reasoning
behaviour expected by the Blueprint and Implementation Programme. These are
static engineering assets — NOT generated by the reasoning engine. Each case is a
sequence of complete canonical EvidenceRecord specs plus the *expected reasoning
evolution* after each step.

The per-step expectations here are machine-checked against the real engine by
``tests/adapters/test_review_dataset.py`` (each field below is asserted against
actual engine output), so the annotations cannot drift from reality. Loading a
case in the harness copies it into a new editable Test Case; the originals are
never modified.

Expectation fields per step (all read from engine state, none re-derived):
  version      — the current WorldModel version after this step (unchanged on a hold)
  committed    — did this step commit a new version (False = model holds)
  inquiry      — is an Inquiry active after this step
  predictions  — hypotheses that hold an active Prediction after this step
  anomaly      — AnomalyResolution disposition, if any: revise | escalate | reject
  uncertainty  — ModelUncertainty trend vs the previous step: first|up|down|flat
"""

from __future__ import annotations

